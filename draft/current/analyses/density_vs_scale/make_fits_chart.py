import sys, json, numpy as np, matplotlib
matplotlib.use("Agg"); import matplotlib.pyplot as plt
sys.path.insert(0,"/workspace/clump_scan/inside_visible/smooth_field")
from lcdm import sigma_TH
F=json.load(open("fits.json"))
V=lambda R: 4/3*np.pi*np.asarray(R,float)**3
Rinv=lambda v: (3*np.asarray(v,float)/(4*np.pi))**(1/3)
R=np.logspace(0,np.log10(20000),200); sig=np.array([sigma_TH(r/1000) for r in R])
def band(f,Rs):
    x=np.log10(V(Rs)); y=f["logA"]-f["alpha"]*x; c=np.array(f["cov"])
    sy=np.sqrt(c[0][0]+x*x*c[1][1]+2*x*c[0][1]); return 10**y,10**(y-sy),10**(y+sy)
fig,(a,b)=plt.subplots(2,1,figsize=(11,10.5),sharex=True,gridspec_kw=dict(hspace=0.06))
for ax in (a,b):
    ax.set_xscale("log"); ax.set_yscale("log"); ax.set_xlim(V(1),V(20000))
    ax.fill_between(V(R),1e-7,3*sig,color="#cfe3f3",zorder=0,label="Standard cosmology: typical range (3σ)")
    ax.axvspan(V(1),V(10),color="0.92",zorder=0.5)
    ax.grid(True,which="major",color="0.88",lw=0.6)
a.set_ylim(1e-4,3e3); b.set_ylim(1e-4,1.0); b.invert_yaxis()
a.set_ylabel("over-density  δ  (+)",fontsize=13); b.set_ylabel("under-density  δ  (−)",fontsize=13)
b.set_yticks([1e-4,1e-3,1e-2,0.1,1]); b.set_yticklabels(["−0.0001","−0.001","−0.01","−0.1","−1 (empty)"])
a.set_yticks([1e-4,1e-3,1e-2,0.1,1,10,100,1000]); a.set_yticklabels(["0.0001","0.001","0.01","0.1","1","10","100","1000"])
b.set_xlabel("region volume (Mpc³)",fontsize=13)
b.set_xticks([1e1,1e3,1e5,1e7,1e9,1e11,1e13])
top=a.secondary_xaxis("top",functions=(Rinv,V)); top.set_xticks([1,10,100,1000,10000]); top.set_xticklabels(["1","10","100","1,000","10,000"])
top.set_xlabel("region radius (Mpc)",fontsize=12)
Rf=np.logspace(np.log10(2),np.log10(20000),200)
# fits
m,lo,hi=band(F["over4"],Rf)
a.fill_between(V(Rf),lo,hi,color="0.6",alpha=0.25,lw=0,zorder=1)
a.plot(V(Rf),m,"--",color="k",lw=2,zorder=2,label=f"Best fit to observed peaks: δ ∝ V$^{{-{F['over4']['alpha']:.2f}}}$")
m,lo,hi=band(F["under_noLH"],Rf)
b.fill_between(V(Rf),lo,hi,color="0.6",alpha=0.25,lw=0,zorder=1)
b.plot(V(Rf),m,"--",color="k",lw=2,zorder=2,label=f"Best fit to observed voids: |δ| ∝ V$^{{-{F['under_noLH']['alpha']:.2f}}}$")
kw=dict(fontsize=10.5)
def obs(ax,r,y,lab,dx=1.6,dy=1.0,ha="left",open_=False):
    ax.plot(V(r),y,"o",color="k",mfc="white" if open_ else "k",ms=8,zorder=5)
    ax.annotate(lab,(V(r),y),xytext=(V(r)*dx,y*dy),ha=ha,va="center",**kw,zorder=6)
obs(a,2.84,645,"Coma cluster",dx=3)
